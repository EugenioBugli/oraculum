"""Generate glstubs.c: one typed fallback for every GL function MuJoCo's glad loader can load.

Usage: python gen_stubs.py MUJOCO_SRC OUT.c

WebAssembly traps when a function pointer is called with the wrong signature, so every name glad
asks for gets a stub with the exact prototype from glad.h. The stubs are weak: glshim.c defines the
functions MuJoCo's renderer really needs, and a stub that is still called at run time logs
"B2 GL unimplemented: <name>" once. A new GL call in a future MuJoCo renderer shows up there.
"""
import re
import sys

src, out = sys.argv[1], sys.argv[2]
glad_h = open(f"{src}/src/render/glad/glad.h").read()
glad_c = open(f"{src}/src/render/glad/glad.c").read()

protos = {pfn: (ret.strip(), args.strip())
          for ret, pfn, args in re.findall(r"typedef (.*?) \(APIENTRYP (PFN\w+)\)\((.*?)\);", glad_h)}
names = dict(re.findall(r'\(\s*(PFN\w+)\s*\)\s*load\("(gl\w+)"\)', glad_c))
names = {name: pfn for pfn, name in names.items()}  # name -> PFN (unique per name)

lines = ['// Generated by gen_stubs.py from MuJoCo\'s glad.h/glad.c. Do not edit.',
         '#include "render/glad/glad.h"',
         'void shim_unimpl(const char* name);', '']
table = []
for name in sorted(names):
    ret, args = protos[names[name]]
    body = f'shim_unimpl("{name}");' + ("" if ret == "void" else f" return ({ret})0;")
    lines.append(f"__attribute__((weak)) {ret} shim_{name}({args}) {{ {body} }}")
    table.append(f'  {{"{name}", (void*)shim_{name}}},')
lines += ["", "const struct shim_entry { const char* name; void* fn; } shim_table[] = {", *table,
          "  {0, 0}", "};", ""]
open(out, "w").write("\n".join(lines))
print(f"{len(table)} GL entry points -> {out}")
